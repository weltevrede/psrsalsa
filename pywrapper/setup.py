verbose = True        # If True, generate some information on terminal
have_numpy = True     # Enable numpy (requires you to have numpy installed)

include_paths = []                  # List of paths in which include files can be found that are not automatically found by the system
library_paths = []                  # List of paths in which libraries can be found that are not automatically found by the system
libraries_list = []                 # List of library dependancies that need to be included during compilation
cflags_extra = []                   # Extra compiler options to pass on
#la_files = []                       # .la libraries to include in linking, used in configure autotools

# Read the information about paths and libraties from .config files generated by the makefile from compiling psrsalsa itself
with open("build/cflags.config", "r") as f:
    line = f.readline()
    for word in line.split():
        if len(word) > 2:
            if word[0] == "-" and word[1] == "I":
                newpath = word[2:]
                if newpath[0] == '/':  # Absolute path
                    include_paths.append(newpath)
                else:
                    include_paths.append("../"+newpath)
            elif word[0] == "-" and word[1] == "L":
                newpath = word[2:]
                if newpath[0] == '/':  # Absolute path
                    library_paths.append(newpath)
                else:
                    library_paths.append("../"+newpath)
            elif word[0] == "-" and word[1] == "l":
                newpath = word[2:]
                if newpath == "psrsalsa":
                    identifier = ""
                    newpath = "psrsalsa" + identifier
                libraries_list.append(newpath)
#            elif ".la" in word:
#                la_files.append(word)
            else:
                cflags_extra.append(word)
    if verbose:
        print("  Loading makefile generated info")
        print("    Include paths:", include_paths)
        print("    Library paths:", library_paths)
        print("    Libraries:", libraries_list)
        print("    Compiler flags:", cflags_extra)
    

if have_numpy == True:
    import numpy
    if verbose:
        print("  Compiling for numpy version:", numpy.version.version)
    cflags_extra.append("-DHAVE_NUMPY")
    # Cannot get numpy version from header/library somehow....
    cflags_extra.append("-DNUMPY_MAJOR_VERSION=%d"%(int(numpy.version.version.split(".")[0])))
    cflags_extra.append("-DNUMPY_MINOR_VERSION=%d"%(int(numpy.version.version.split(".")[1])))
    cflags_extra.append("-DNPY_NO_DEPRECATED_API=NPY_1_7_API_VERSION")  # To avoid warning about depreciated Numpy C-Api (something with how setuptools work)
    if verbose:
        print("  Adding include path:", numpy.get_include())
    include_paths.append(numpy.get_include())  # numpy/ndarrayobject.h should be there
    
version    = Extension("version",    sources=["src/version_py.c"],    include_dirs=include_paths,library_dirs=library_paths,libraries=libraries_list,extra_compile_args=cflags_extra)
io         = Extension("io",         sources=["src/io_py.c"],         include_dirs=include_paths,library_dirs=library_paths,libraries=libraries_list,extra_compile_args=cflags_extra)
genops     = Extension("genops",     sources=["src/genops_py.c"],     include_dirs=include_paths,library_dirs=library_paths,libraries=libraries_list,extra_compile_args=cflags_extra)
spec       = Extension("spec",       sources=["src/spec_py.c"],       include_dirs=include_paths,library_dirs=library_paths,libraries=libraries_list,extra_compile_args=cflags_extra)
fold       = Extension("fold",       sources=["src/fold_py.c"],       include_dirs=include_paths,library_dirs=library_paths,libraries=libraries_list,extra_compile_args=cflags_extra)
pol        = Extension("pol",        sources=["src/pol_py.c"],        include_dirs=include_paths,library_dirs=library_paths,libraries=libraries_list,extra_compile_args=cflags_extra)
vonMises   = Extension("vonMises",   sources=["src/vonMises_py.c"],   include_dirs=include_paths,library_dirs=library_paths,libraries=libraries_list,extra_compile_args=cflags_extra)



print("\n Starting compilation\n")



class specialised_build_ext(build_ext, object):
    def build_extension(self, ext):
        ret = super(specialised_build_ext, self).build_extension(ext)
        if ext.name == "io":   # Make sure this is only done once, after directory structure is generated after building the first module
            print("Creating __init__.py")
            shutil.copyfile(os.path.join('src','__init__.py'), os.path.join(self.build_lib,'psrsalsa',"__init__.py"))
            print("Creating psrchive extension.py")
            newpath = os.path.join(self.build_lib,'psrsalsa','psrchive')
            os.mkdir(newpath)
            shutil.copyfile(os.path.join('src','psrchive','__init__.py'), os.path.join(self.build_lib,'psrsalsa','psrchive',"__init__.py"))
            shutil.copyfile(os.path.join('src','psrchive','io.py'), os.path.join(self.build_lib,'psrsalsa','psrchive',"io.py"))
        return ret
        
